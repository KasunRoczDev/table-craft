/** What does not change with the scheme: fonts, radii and timing, from the same tokens as the app. */
export function sharedProperties(): Record<string, string> {
  return {
    "--sl-font": SYSTEM_UI_FONT,
    "--sl-font-mono": SYSTEM_MONO_FONT,
    "--tc-font-ui": SYSTEM_UI_FONT,
    "--tc-font-mono": SYSTEM_MONO_FONT,
    "--tc-radius-island": `${COMFORTABLE_DENSITY.islandRadiusPx}px`,
    "--tc-radius-popover": `${ISLANDS_POPOVER_RADIUS_PX}px`,
    "--tc-radius-key": `${TOOLTIP_RADIUS_PX}px`,
    "--tc-gap-island": `${COMFORTABLE_DENSITY.islandGapPx}px`,
    "--tc-motion-fast": `${MOTION.full.fastMs}ms`,
    "--tc-motion-base": `${MOTION.full.baseMs}ms`,
  };
}

function block(selector: string, properties: Record<string, string>): string {
  const lines = Object.entries(properties).map(([name, value]) => `  ${name}: ${value};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

/** The site's stylesheet of tokens: Dark on `:root`, Light under Starlight's `data-theme="light"`. */
export function tokensCss(dark: ColorTokens, light: ColorTokens): string {
  return [
    "/* Generated by packages/website/scripts/sync.ts from packages/desktop/src/appearance/themes.ts. */\n",
    block(":root", { ...sharedProperties(), ...themeProperties(dark), "color-scheme": "dark" }),
    block(LIGHT_THEME_SELECTOR, { ...themeProperties(light), "color-scheme": "light" }),
  ].join("\n");
}

export interface CodeTheme {
  name: string;
  type: "dark" | "light";
  colors: Record<string, string>;
  tokenColors: { scope: string[]; settings: { foreground: string; fontStyle?: string } }[];
}

const SCOPES = {
  comment: ["comment", "punctuation.definition.comment"],
  keyword: ["keyword", "storage", "storage.type", "storage.modifier", "constant.language", "support.type.primitive"],
  string: ["string", "punctuation.definition.string", "markup.inline.raw"],
  number: ["constant.numeric", "constant.character.escape"],
  identifier: ["variable.other.property", "support.type.property-name", "meta.object-literal.key", "entity.name.tag"],
  operator: ["keyword.operator", "punctuation"],
  variable: ["variable.parameter", "variable.other.readwrite", "entity.name.function", "support.function"],
} as const;

/** A TextMate theme for Expressive Code from one scheme's `syntax` tokens, so code reads as in the console. */
export function codeTheme(name: string, type: CodeTheme["type"], colors: ColorTokens): CodeTheme {
  const { syntax } = colors;
  return {
    name,
    type,
    colors: {
      "editor.background": colors.panel,
      "editor.foreground": colors.ink,
      "editor.selectionBackground": colors.selection,
      "editorLineNumber.foreground": colors.inkMuted,
      "editorGroupHeader.tabsBackground": colors.panel,
      "tab.activeBackground": colors.panel,
      "tab.activeForeground": colors.ink,
      "tab.activeBorderTop": colors.accent,
      "titleBar.border": colors.border,
      "terminal.background": colors.panel,
      "terminal.foreground": colors.ink,
      focusBorder: colors.border,
    },
    tokenColors: [
      { scope: [...SCOPES.operator], settings: { foreground: syntax.operator } },
      { scope: [...SCOPES.keyword], settings: { foreground: syntax.keyword } },
      { scope: [...SCOPES.string], settings: { foreground: syntax.string } },
      { scope: [...SCOPES.number], settings: { foreground: syntax.number } },
      { scope: [...SCOPES.identifier], settings: { foreground: syntax.identifier } },
      { scope: [...SCOPES.variable], settings: { foreground: syntax.variable } },
      { scope: [...SCOPES.comment], settings: { foreground: syntax.comment, fontStyle: "italic" } },
    ],
  };
}

export function codeThemes(dark: ColorTokens, light: ColorTokens): [CodeTheme, CodeTheme] {
  return [codeTheme("tablecraft-dark", "dark", dark), codeTheme("tablecraft-light", "light", light)];
}
